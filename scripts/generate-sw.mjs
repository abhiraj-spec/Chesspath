// Runs after `next build`: writes out/sw.js, a service worker that precaches the whole static
// export (pages, scripts, styles, fonts and the Stockfish engine) so the app works offline.
import { createHash } from "node:crypto";
import { readdirSync, readFileSync, statSync, writeFileSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const out = join(root, "out");
if (!existsSync(out)) {
  console.error("[generate-sw] out/ not found. Run `next build` first.");
  process.exit(1);
}
const files = [];
const walk = (dir) => {
  for (const name of readdirSync(dir)) {
    const p = join(dir, name);
    if (statSync(p).isDirectory()) walk(p);
    else files.push(p);
  }
};
walk(out);
const hash = createHash("sha256");
const urls = [];
for (const f of files.sort()) {
  const rel = "/" + relative(out, f).split(sep).join("/");
  if (rel === "/sw.js" || rel.endsWith(".txt") || rel.endsWith(".map")) continue;
  hash.update(rel);
  hash.update(readFileSync(f));
  // Pages are requested as /path/ (trailingSlash export), so cache the directory URL.
  urls.push(rel.endsWith("/index.html") ? rel.slice(0, -"index.html".length) : rel);
}
const version = hash.digest("hex").slice(0, 12);
const sw = `// Generated by scripts/generate-sw.mjs. Do not edit.
const VERSION = ${JSON.stringify(version)};
const CACHE = "chesspath-" + VERSION;
const PRECACHE = ${JSON.stringify(urls)};

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then(async (cache) => {
      // Add in small batches so one failure does not abort the whole install.
      for (let i = 0; i < PRECACHE.length; i += 20) {
        await Promise.all(PRECACHE.slice(i, i + 20).map((u) => cache.add(u).catch(() => undefined)));
      }
    }).then(() => self.skipWaiting()),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys().then((keys) => Promise.all(keys.filter((k) => k.startsWith("chesspath-") && k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()),
  );
});

self.addEventListener("fetch", (event) => {
  const req = event.request;
  if (req.method !== "GET") return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;
  if (req.mode === "navigate") {
    // Network first for pages (fresh content when online), cached copy when offline.
    event.respondWith(
      fetch(req)
        .then((res) => {
          const copy = res.clone();
          caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          return res;
        })
        .catch(async () => {
          const cache = await caches.open(CACHE);
          const path = url.pathname.endsWith("/") ? url.pathname : url.pathname + "/";
          return (await cache.match(path)) || (await cache.match(url.pathname)) || (await cache.match("/")) || Response.error();
        }),
    );
    return;
  }
  // Static assets are content-hashed: cache first.
  event.respondWith(
    caches.match(req, { ignoreSearch: url.pathname.startsWith("/_next/") }).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok && (url.pathname.startsWith("/_next/") || url.pathname.startsWith("/engine/"))) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy)).catch(() => {});
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(out, "sw.js"), sw);
console.log(`[generate-sw] ${urls.length} files precached, version ${version}`);
